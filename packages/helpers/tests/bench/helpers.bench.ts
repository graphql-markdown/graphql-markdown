import { describe, expect, test } from "vitest";

import { buildSchema } from "graphql/utilities";

import {
  directiveDescriptor,
  directiveTag,
  formatMarkdownFrontmatter,
  indentMarkdownLines,
  mergeFrontmatterLines,
  quoteMarkdownLines,
} from "../../src";
import { interpolate } from "../../src/utils/interpolate";

const TYPE_COUNT = 100;

const typeDefinitions = Array.from({ length: TYPE_COUNT }, (_, index) => {
  return `type Entity${index} @auth(role: "admin${index}", major: ${index}, minor: 1) {
  id: ID!
  name: String
}`;
}).join("\n\n");

const schema = buildSchema(`
"""
Requires the \${role} role since \${major}.\${minor}
"""
directive @auth(role: String!, major: Int, minor: Int) on OBJECT

${typeDefinitions}

type Query {
  entity: Entity0
}
`);

const directive = schema.getDirective("auth")!;
const types = Array.from({ length: TYPE_COUNT }, (_, index) => {
  return schema.getType(`Entity${index}`);
});

const TEMPLATE =
  "Requires the `${role}` role (since ${version.major}.${version.minor}, ${missing.value})";
const DIRECTIVE_TEMPLATE =
  "Requires the `${role}` role (since ${major}.${minor})";
const variables = {
  description: "auth",
  role: "admin",
  version: { major: 2, minor: 1 },
};

const MARKDOWN = Array.from({ length: 200 }, (_, index) => {
  return index % 5 === 0 ? "" : `Line ${index} of a **markdown** description.`;
}).join("\n");

const frontMatterProps = {
  id: "film",
  title: "Film",
  sidebar_position: 3,
  hide_table_of_contents: false,
};
const formattedFrontMatter = [
  "# generated by graphql-markdown",
  'title: "Film"',
  "slug: /types/objects/film",
  "tags: [graphql, object]",
  "description: The Film object type",
];

describe("@graphql-markdown/helpers", () => {
  test("directives", async ({ bench }) => {
    expect(
      directiveDescriptor(directive, types[0], DIRECTIVE_TEMPLATE),
    ).toContain("admin0");

    await bench.compare(
      bench("directiveDescriptor for 100 types", () => {
        for (const type of types) {
          directiveDescriptor(directive, type);
        }
      }),
      bench("directiveDescriptor with template for 100 types", () => {
        for (const type of types) {
          directiveDescriptor(directive, type, DIRECTIVE_TEMPLATE);
        }
      }),
      bench("directiveTag for 100 types", () => {
        for (const type of types) {
          directiveTag(directive, type);
        }
      }),
      bench("interpolate template", () => {
        interpolate(TEMPLATE, variables, "n/a");
      }),
    );
  });

  test("markdown", async ({ bench }) => {
    expect(quoteMarkdownLines(MARKDOWN)).toBeTruthy();

    await bench.compare(
      bench("quoteMarkdownLines (200 lines)", () => {
        quoteMarkdownLines(MARKDOWN);
      }),
      bench("indentMarkdownLines (200 lines)", () => {
        indentMarkdownLines(MARKDOWN, 4);
      }),
      bench("merge and format frontmatter", () => {
        formatMarkdownFrontmatter(
          mergeFrontmatterLines(frontMatterProps, formattedFrontMatter),
        );
      }),
    );
  });
});
